import { test, expect } from "@playwright/test";
import type { View } from "../src/contracts";

test("Inspect a source player without changing the incident, clock or proof scope", async ({ page, request }, info) => {
  await page.goto("/?view=studio&scenario=line-shift&clock=3360");
  const choose = page.getByLabel("Inspect source player", { exact: true });
  await expect(choose).toBeVisible({ timeout: 60000 });
  const view: View = await (await request.get("/api/view?scenario=line-shift&clock=3360&audience=fan")).json();
  const player = view.frame!.players.find(row => !row.goalkeeper)!;
  let proofRequests = 0;
  page.on("request", req => { if (req.url().includes("/api/proof?")) proofRequests++; });
  await choose.selectOption(player.id);
  const panel = page.getByRole("region", { name: "Source position inspector" });
  await expect(panel).toContainText(player.id);
  await expect(page.getByTestId("source-player-x")).toHaveText(`${player.x.toFixed(2)} m`);
  await expect(page.getByTestId("source-player-y")).toHaveText(`${player.y.toFixed(2)} m`);
  await expect(panel.locator("[data-frame-id]")).toHaveAttribute("data-frame-id", view.frame!.frame_id);
  await expect(page.locator(".pitch-contributor-ring")).toHaveCount(1);
  await expect(page.getByTestId("clock")).toHaveText("56:00");
  expect(proofRequests).toBe(0);
  await page.getByRole("button", { name: "Open Proof Lens", exact: true }).click();
  await expect(page.locator(".summary-support")).toContainText("59 source frames");
  await expect(page.locator(".aggregate-values")).toContainText("+10.01");
  await page.keyboard.press("Escape");
  await choose.scrollIntoViewIfNeeded();
  await page.screenshot({ path: info.outputPath("source-player-inspection.png"), animations: "disabled" });
});

test("Player inspection pauses playback and clears across source fixtures", async ({ page, request }, info) => {
  await page.goto("/?view=studio&scenario=native-goals&clock=1611");
  const choose = page.getByLabel("Inspect source player", { exact: true });
  await expect(choose).toBeVisible({ timeout: 60000 });
  const id = await choose.locator("option").nth(1).getAttribute("value");
  await page.getByLabel("Playback speed").selectOption("12");
  await page.getByRole("button", { name: "Play replay", exact: true }).click();
  await expect.poll(async () => Number(await page.getByLabel("Replay clock", { exact: true }).inputValue())).toBeGreaterThan(1611);
  await choose.selectOption(id!);
  await expect(page.getByRole("button", { name: "Play replay", exact: true })).toBeVisible();
  const clock = Number(await page.getByLabel("Replay clock", { exact: true }).inputValue());
  const oracle: View = await (await request.get(`/api/view?scenario=native-goals&clock=${clock}&audience=fan`)).json();
  const player = oracle.frame!.players.find(row => row.id === id)!;
  await expect(page.getByTestId("source-player-x")).toHaveText(`${player.x.toFixed(2)} m`);
  await page.getByRole("button", { name: "Select The opening goal", exact: true }).click();
  await expect(page.getByRole("region", { name: "Source position inspector" })).toContainText("Event-only fixtures show recorded ball locations");
  await expect(choose).toHaveCount(0);
  await expect(page.getByTestId("source-player-x")).toHaveCount(0);
  await page.getByRole("button", { name: "Select A higher line, proved", exact: true }).click();
  await expect(choose).toBeVisible();
  await expect(choose).toHaveValue("");
  await page.getByRole("button", { name: "Switch to dark theme" }).click();
  const next = page.getByRole("button", { name: "Next source player", exact: true });
  await next.focus();
  await page.keyboard.press("Enter");
  await expect(page.getByTestId("source-player-x")).toBeVisible();
  await expect(choose).toHaveValue(oracle.frame!.players[0].id);
  await page.getByRole("button", { name: "Previous source player", exact: true }).focus();
  await page.keyboard.press("Space");
  const line: View = await (await request.get("/api/view?scenario=line-shift&clock=3360&audience=fan")).json();
  await expect(choose).toHaveValue(line.frame!.players.at(-1)!.id);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: info.outputPath("source-player-dark.png"), animations: "disabled" });
});
